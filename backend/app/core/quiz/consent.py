"""
出题前的「学生同意」判定 —— **全库唯一实现**（2026-09-30）。

为什么要这一层
    模型对"该不该出题"的判断极不稳（真机两轮事故）：
      · 连着两轮口头承诺"题目稍等一下会自动推给你"，`quiz_generate` 调用数 0 → 学生干等；
      · 把 0/10 讲成"Bingo，答对了"，顺脚往下考。
    → 把决策权交回学生：**先问一句、按他的回答行动**；"没同意就出题"在服务端硬拦。

判定只用**本轮**学生输入（同轮判定，不需要跨轮记忆）：
学生回应"要不要出题"的下一轮，他说的那句本来就是同意句；主动说"考考我"也是同一轮 —— 两种都盖得住。

识别范围刻意收窄：只看**短回复**、且必须命中明确的同意/拒绝词；长句一律判"不确定"。
不确定 = 不放行出题（让模型先去问一句）—— **宁可多问一句，也不要擅自出题**。

谁在用
    · `chat_service._stash_quiz_consent`  ← 对话路径把结论挂到 kg 上（每请求新建的实例）
    · `agent_tools/tools/quiz_generate`   ← 出题前读它做硬拦
    · `scripts/smoke_*` / 测试 / 节点详情「按小节出题」接口：**没有这个上下文 → 一律放行**。
"""

import re

CONSENT_QUIZ_YES = "yes"       # 明确同意出题
CONSENT_QUIZ_NO = "no"         # 明确不要（或要求先讲）
CONSENT_QUIZ_UNKNOWN = ""      # 不确定 / 没上下文 → 不放行，但也不算拒绝

_QUIZ_CONSENT_MAX_CHARS = 12   # 超过这个长度就不是"对提问的短回答"了，不猜

# 拒绝词**先于**同意词匹配 —— 否则"不要"会被"要"命中（中文否定的常见坑）
_NO_WORDS = (
    "不要", "不用", "不行", "不想", "别出", "别急", "先别", "不了", "算了",
    "先讲", "再讲", "讲讲", "讲一下", "讲一遍", "先解释", "先看",
    "听不懂", "不会", "不懂", "不清楚", "忘了", "等等", "等一下", "复习",
)
_YES_WORDS = (
    "好的", "好啊", "好了", "好", "行", "可以", "嗯", "对", "是的", "要",
    "来吧", "开始", "继续", "出吧", "出题", "考我", "考考我", "测", "练",
    "试试", "没问题", "都行", "随便", "ok", "yes",
    # 主动续练的常见说法（"答错了，再来一道"）
    "再来", "再出", "再练", "再考",
)


def classify_quiz_consent(text: str) -> str:
    """
    学生这一句是不是"同意出题" → `"yes"` / `"no"` / `""`（不确定）。

    任何异常都归为不确定（不清楚就不放行，安全侧）。
    """
    try:
        t = re.sub(r"[\s，。、；：！？,.!?;:（）()\"']", "", str(text or "")).lower()
    except Exception:  # noqa: BLE001
        return CONSENT_QUIZ_UNKNOWN
    if not t or len(t) > _QUIZ_CONSENT_MAX_CHARS:
        return CONSENT_QUIZ_UNKNOWN
    if any(w in t for w in _NO_WORDS):
        return CONSENT_QUIZ_NO
    if any(w in t for w in _YES_WORDS):
        return CONSENT_QUIZ_YES
    return CONSENT_QUIZ_UNKNOWN


# 给模型看的两种回执（工具层直接用，避免两处各写一版文案）
def refusal_text(student_input: str) -> str:
    """学生明确说"先讲 / 不要"时，拒绝出题并指回讲解。"""
    return ("⛔ 学生这一轮明确表示**不要出题 / 先讲**"
            f"（他说的是「{student_input[:40]}」）—— 不要出题。"
            "按他的意思把这一节（或这个问题）讲清楚，讲完再问一句要不要出题验证。")


def ask_first_text(student_input: str) -> str:
    """学生没有明确同意时，拒绝出题并要求先问一句。"""
    return ("⛔ 学生这一轮**没有明确同意出题**"
            f"（他说的是「{student_input[:40]}」）—— 不要直接出题。"
            "先用一句话问「要不要出一道题检验一下？」，他答应后（下一轮）再调本工具。"
            "⛔ 也**不要**用\"题目稍等，我这就出\"这种话代替提问。")
